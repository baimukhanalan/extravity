/**
 * Dictionary-based localization. Russian is the source of truth: `Dict` is
 * derived from it, so a missing key in kk/en is a type error rather than a
 * string that silently falls back at runtime.
 *
 * Server components read the active locale with `getLocale()` (lib/locale.ts)
 * and pass the slice they need into client components as props — no context
 * provider, no client-side bundle of all three languages.
 */

export const LOCALES = ["ru", "kk", "en"] as const;
export type Locale = (typeof LOCALES)[number];

export const LOCALE_NAMES: Record<Locale, string> = {
  ru: "Русский",
  kk: "Қазақша",
  en: "English",
};

export const DEFAULT_LOCALE: Locale = "ru";

export function isLocale(value: string | undefined | null): value is Locale {
  return !!value && (LOCALES as readonly string[]).includes(value);
}

